function createFoodIllustration(foodId) {
    const namespace = 'http://www.w3.org/2000/svg';
    const svg = document.createElementNS(namespace, 'svg');
    const attributes = {
        class: 'card-icon', viewBox: '0 0 64 64', fill: 'none',
        stroke: 'currentColor', 'stroke-width': '2.5',
        'stroke-linecap': 'round', 'stroke-linejoin': 'round',
        'aria-hidden': 'true', focusable: 'false'
    };
    Object.entries(attributes).forEach(([key, value]) => svg.setAttribute(key, value));
    (FOOD_ILLUSTRATIONS[foodId] || []).forEach(([tag, attributes]) => {
        const shape = document.createElementNS(namespace, tag);
        Object.entries(attributes).forEach(([key, value]) => shape.setAttribute(key, value));
        svg.appendChild(shape);
    });
    return svg;
}

function renderCards(filter = '') {
    FOOD_GRID.textContent = '';
    const normalizedFilter = normalizeSearchText(filter);
    const filtered = foodData.filter(food => {
        const matchesSearch = normalizeSearchText(food.name).includes(normalizedFilter);
        const matchesCategory = currentCategory === 'all' || food.category === currentCategory;
        return matchesSearch && matchesCategory;
    });

    RESULT_COUNT.textContent = `${filtered.length}件の食材`;
    EMPTY_MESSAGE.hidden = filtered.length !== 0;
    CLEAR_SEARCH.hidden = SEARCH_INPUT.value.length === 0;

    filtered.forEach(food => {
        const card = document.createElement('button');
        card.type = 'button';
        card.dataset.foodId = String(food.id);
        card.className = 'card';
        card.appendChild(createFoodIllustration(food.id));
        const parts = [
            ['card-name', food.name],
            ['card-category', food.category],
            ['card-action', '詳細を見る →']
        ];
        parts.forEach(([className, text]) => {
            const span = document.createElement('span');
            span.className = className;
            span.textContent = text;
            card.appendChild(span);
        });
        card.onclick = () => showDetail(food, card);
        FOOD_GRID.appendChild(card);
    });
}

function showDetail(food, trigger, fromHistory = false) {
    if (historyNavigationPending || historyClosePending) return;
    if (!fromHistory) {
        if (DETAIL_MODAL.open) return;
        // 元の履歴エントリーは変更せず、新しいエントリーに状態を保持する。
        try {
            history.pushState({
                mekikiDetail: { version: 1, foodId: food.id },
                previousState: history.state
            }, '');
        } catch (error) {
            // 履歴が利用できない環境でも、詳細の閲覧と通常の閉じる操作を保つ。
            console.warn('詳細画面の履歴を追加できませんでした。');
        }
    }
    detailTrigger = trigger;
    document.getElementById('foodTitle').textContent = food.name;

    // 見分け方
    const selectInfo = document.getElementById('selectInfo');
    selectInfo.innerHTML = food.selection.map(item => `
        <div class="info-item">
            <span class="badge bg-select">Check</span> ${item}
        </div>
    `).join('');

    // 保存方法
    const storeInfo = document.getElementById('storeInfo');
    storeInfo.innerHTML = Object.entries(food.storage).map(([type, method]) => `
        <div class="info-item">
            <span class="badge bg-store">${type}</span> ${method}
        </div>
    `).join('');

    // 出典
    const sourceLinks = document.getElementById('sourceLinks');
    sourceLinks.innerHTML = '出典：<br>' + food.sources.map(s => `<a href="${s.url}" target="_blank" rel="noopener noreferrer">${s.name} <i class="fa-solid fa-arrow-up-right-from-square"></i></a>`).join(' | ');

    if (!DETAIL_MODAL.open) DETAIL_MODAL.showModal();
    DETAIL_MODAL.querySelector('.modal-content').scrollTop = 0;
}

// Event Listeners
SEARCH_INPUT.oninput = (e) => renderCards(e.target.value);

CLEAR_SEARCH.onclick = () => {
    SEARCH_INPUT.value = '';
    renderCards();
    SEARCH_INPUT.focus();
};

CATEGORY_TABS.onclick = (e) => {
    const tab = e.target.closest('.tab');
    if (tab && CATEGORY_TABS.contains(tab)) {
        CATEGORY_TABS.querySelectorAll('.tab').forEach(t => {
            const selected = t === tab;
            t.classList.toggle('active', selected);
            t.setAttribute('aria-pressed', String(selected));
        });
        currentCategory = tab.dataset.category;
        renderCards(SEARCH_INPUT.value);
    }
};

CLOSE_MODAL.onclick = () => {
    DETAIL_MODAL.close();
};

DETAIL_MODAL.onclick = (e) => {
    if (e.target === DETAIL_MODAL) {
        const bounds = DETAIL_MODAL.getBoundingClientRect();
        if (e.clientX < bounds.left || e.clientX > bounds.right ||
            e.clientY < bounds.top || e.clientY > bounds.bottom) {
            DETAIL_MODAL.close();
        }
    }
};

DETAIL_MODAL.addEventListener('close', () => {
    if (historyClosePending) {
        historyClosePending = false;
    } else if (detailFoodFromState(history.state)) {
        historyNavigationPending = true;
        history.back();
    }
    if (detailTrigger && detailTrigger.isConnected) detailTrigger.focus();
    detailTrigger = null;
    // closeイベント待ちに「進む」が発生した場合も、現在の履歴に合わせる。
    if (!historyNavigationPending) syncDetailWithHistory();
});

function syncDetailWithHistory() {
    const food = detailFoodFromState(history.state);
    if (food) {
        const card = FOOD_GRID.querySelector(`[data-food-id="${food.id}"]`);
        showDetail(food, card || SEARCH_INPUT, true);
    } else if (DETAIL_MODAL.open) {
        historyClosePending = true;
        DETAIL_MODAL.close();
    }
}

window.addEventListener('popstate', () => {
    historyNavigationPending = false;
    syncDetailWithHistory();
});

// Initial Render
renderCards();
syncDetailWithHistory();
